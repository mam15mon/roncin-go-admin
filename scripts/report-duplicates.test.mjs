test('基线对比识别新增、消失与成员变化', () => {
  const group = (language, fingerprint, members) => ({
    language,
    mode: 'exact',
    fingerprint,
    nodes: 10,
    coveredNodes: 20,
    fileCount: members.length,
    evidence: 'x',
    members: members.map(([path, startLine, endLine, symbol]) => ({
      path,
      startLine,
      endLine,
      symbol,
    })),
  });
  const same = group('go', 'aaa', [
    ['a.go', 1, 9, 'A'],
    ['b.go', 1, 9, 'B'],
  ]);
  const baseline = [same, group('go', 'gone', [['c.go', 1, 9, 'C']])];
  const grown = group('go', 'aaa', [
    ['a.go', 1, 9, 'A'],
    ['b.go', 1, 9, 'B'],
    ['d.go', 5, 13, 'D'],
  ]);
  const fresh = group('javascript', 'new', [['e.ts', 1, 9, 'E']]);
  const delta = baselineDelta([same, grown, fresh], baseline);
  assert.deepEqual(
    delta.added.map((item) => item.fingerprint),
    ['new'],
  );
  assert.deepEqual(
    delta.resolved.map((item) => item.fingerprint),
    ['gone'],
  );
  assert.equal(delta.changed.length, 1);
  assert.equal(delta.changed[0].current.members.length, 3);
  assert.equal(delta.changed[0].baseline.members.length, 2);
  const empty = baselineDelta([same], [same]);
  assert.deepEqual(empty, { added: [], resolved: [], changed: [] });
  const text = renderText({
    minNodes: 60,
    statistics: {
      scannedFiles: { javascript: 1, go: 1 },
      excludedFiles: {},
      excludedDirectories: 0,
      functions: 1,
      eligibleFunctions: 1,
      exactOnlyFunctions: 0,
    },
    limitations: [],
    groups: [fresh],
    errors: [],
    baseline: { path: 'base.json', ...delta },
  });
  assert.match(text, /新增 1 组、消失 1 组、成员变化 1 组/);
  assert.match(text, /\+ 新增 \[javascript\/exact\]/);
  assert.match(text, /- 消失 \[go\/exact\]/);
  assert.match(text, /~ 成员变化 \[go\/exact\]/);
  assert.match(text, /旧 a\.go:1-9 A/);
  assert.match(text, /新 d\.go:5-13 D/);
});

test('只排除文件头生成注释，字符串及代码后的标记不漏扫', (t) => {
  const { root, put } = fixture(t);
  for (const [name, source] of Object.entries({
    string: 'export function show() { return "@generated"; }',
    template: 'export const text = `Code generated x DO NOT EDIT`;',
    later: 'export const a = 1; // @generated',
    inside: 'export function f() { /* @generated */ return 1; }',
  }))
    put(`web/src/${name}.ts`, source);
  put(
    'server/hand.go',
    'package hand\nfunc show() string { return "@generated" }',
  );
  for (const [name, source] of Object.entries({
    line: '// @generated\nexport const a = 1;',
    block: '\uFEFF /** 版权 */\n/**\n * @generated\n */\nexport const a = 1;',
    shebang:
      '#!/usr/bin/env node\n// This file is auto-generated\nexport const a = 1;',
    long: `/* ${'版权'.repeat(3000)} */\n// 此文件为自动生成\nexport const a = 1;`,
  }))
    put(`web/src/${name}.ts`, source);
  put(
    'server/generated.go',
    '//go:build linux\n\n// Code generated by ent. DO NOT EDIT.\npackage generated',
  );
  const result = collectSources(root);
  assert.equal(result.sources.javascript.length, 4);
  assert.equal(result.sources.go.length, 1);
  assert.equal(result.statistics.excludedFiles.生成标记, 5);
  assert.deepEqual(result.errors, []);
});

test('基线要求相同扫描配置与有效成员，拒绝旧格式及失败扫描', (t) => {
  const { root, put } = fixture(t);
  put(
    'web/src/a.ts',
    'function a(x) { return x + 1; } function b(y) { return y + 1; }',
  );
  const report = scan(root, 1);
  const baseline = baselineSnapshot(report);
  validateBaseline(baseline, reportConfig(1));
  assert.deepEqual(Object.keys(baseline), [
    'version',
    'modes',
    'minNodes',
    'roots',
    'groups',
  ]);
  assert.deepEqual(baselineDelta(report.groups, baseline.groups), {
    added: [],
    resolved: [],
    changed: [],
  });
  for (const patch of [
    { version: 1 },
    { modes: ['exact'] },
    { minNodes: 60 },
    { roots: ['web/src'] },
    { errors: [{ message: '失败' }] },
    { groups: [null] },
    { groups: [{ ...baseline.groups[0], members: [] }] },
    { groups: [{ ...baseline.groups[0], members: [null, null] }] },
    { groups: [{ ...baseline.groups[0], fingerprint: 'invalid' }] },
  ])
    assert.throws(
      () => validateBaseline({ ...baseline, ...patch }, reportConfig(1)),
      /基线/,
    );
  assert.throws(() => validateBaseline({ groups: [] }), /version/);
  assert.throws(
    () => baselineSnapshot({ ...report, errors: [{}] }),
    /禁止覆盖基线/,
  );
  assert.throws(
    () => baselineSnapshot({ ...report, errors: undefined }),
    /禁止覆盖基线/,
  );
  const path = join(root, 'baseline.json');
  writeFileSync(path, JSON.stringify(baseline));
  const output = join(root, 'report.txt');
  writeFileSync(output, '保留原报告');
  const child = spawnSync(
    process.execPath,
    ['scripts/report-duplicates.mjs', '--baseline', path, '--output', output],
    { encoding: 'utf8' },
  );
  assert.notEqual(child.status, 0);
  assert.match(child.stderr, /minNodes/);
  assert.equal(readFileSync(output, 'utf8'), '保留原报告');
});

test('失败扫描不能覆盖基线，成功生成保留配置元数据', (t) => {
  const { root, put } = fixture(t);
  const path = join(root, 'baseline.json');
  writeFileSync(path, '保留原有审查快照');
  put('web/src/broken.ts', 'function broken(');
  assert.throws(() => writeBaseline(path, scan(root)), /禁止覆盖基线/);
  assert.equal(readFileSync(path, 'utf8'), '保留原有审查快照');
  put('web/src/broken.ts', 'function good() { return 1; }');
  writeBaseline(path, scan(root));
  const baseline = JSON.parse(readFileSync(path, 'utf8'));
  validateBaseline(baseline);
  assert.equal(baseline.version, 2);
  assert.equal(baseline.minNodes, 60);
});
