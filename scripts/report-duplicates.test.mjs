import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import test from 'node:test';
import { extractFunctions } from '../web/scripts/duplicate-functions.mjs';
import {
  baselineDelta,
  collectSources,
  groupFunctions,
  renderText,
  scan,
} from './report-duplicates.mjs';
function fixture(t) {
  const root = mkdtempSync(join(tmpdir(), 'duplicate-test-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  mkdirSync(join(root, 'web/src'), { recursive: true });
  mkdirSync(join(root, 'server'), { recursive: true });
  return {
    root,
    put(path, source) {
      const absolute = join(root, path);
      mkdirSync(join(absolute, '..'), { recursive: true });
      writeFileSync(absolute, source);
    },
  };
}
test('排除生成物、测试、依赖与构建，保留手写 Ent schema', (t) => {
  const { root, put } = fixture(t);
  for (const path of ['web/src/a.ts', 'server/internal/data/ent/schema/a.go'])
    put(path, '');
  for (const path of [
    'web/src/a.test.ts',
    'server/a_test.go',
    'web/src/a.generated.ts',
    'server/a.pb.go',
    'web/src/node_modules/a.ts',
    'web/src/services/roncin/a.ts',
    'server/vendor/a.go',
    'server/dist/a.go',
  ])
    put(path, '');
  put('server/generated.go', '// Code generated by ent. DO NOT EDIT.');
  const result = collectSources(root);
  assert.equal(result.sources.javascript.length, 1);
  assert.equal(result.sources.go.length, 1);
  assert.equal(result.errors.length, 0);
});
test('阈值、同语言分组、稳定顺序、精确组去重及最大函数优先', () => {
  const source = 'function a(x) { const next = x+1; return () => next+1; }';
  const records = [
    ...extractFunctions(source, 'b.ts'),
    ...extractFunctions(source.replace('function a', 'function b'), 'a.ts'),
  ];
  assert.equal(groupFunctions(records, 9999).length, 0);
  const groups = groupFunctions(records, 1);
  assert.equal(groups.length, 1);
  assert.equal(groups[0].mode, 'exact');
  assert.equal(groups[0].members[0].path, 'a.ts');
  assert.deepEqual(groupFunctions([...records].reverse(), 1), groups);
  assert.equal(
    groupFunctions([records[0], { ...records[0], language: 'go' }], 1).length,
    0,
  );
});
test('改名组包含依据，报告不泄漏源码及规范化全文', () => {
  const records = [
    ...extractFunctions('function a(x){ return x+1; }', 'a.ts'),
    ...extractFunctions('function b(y){ return y+1; }', 'b.ts'),
  ];
  const groups = groupFunctions(records, 1);
  assert.equal(groups.length, 1);
  assert.equal(groups[0].mode, 'renamed');
  assert.ok(groups[0].evidence);
  assert.equal('exact' in groups[0].members[0], false);
  assert.equal('renamed' in groups[0].members[0], false);
});
test('无 Go 文件时不需要 Go，解析失败保留明确错误，输出稳定', (t) => {
  const { root, put } = fixture(t);
  put('web/src/broken.ts', 'function broken(');
  const result = scan(root, 1);
  assert.equal(result.errors.length, 1);
  assert.equal(result.errors[0].path, 'web/src/broken.ts');
  assert.equal(JSON.stringify(scan(root, 1)), JSON.stringify(result));
  assert.equal(renderText(result), renderText(scan(root, 1)));
  assert.match(renderText(result), /零候选不代表/);
  assert.match(renderText(result), /错误/);
});
test('CLI 无效参数必须非零退出', () => {
  for (const args of [
    ['--min-nodes', '0'],
    ['--format', 'csv'],
    ['--output'],
    ['--baseline'],
    ['--unknown'],
  ]) {
    const child = spawnSync(
      process.execPath,
      ['scripts/report-duplicates.mjs', ...args],
      { encoding: 'utf8' },
    );
    assert.notEqual(child.status, 0);
    assert.match(child.stderr, /重复扫描失败/);
  }
  for (const [baseline, message] of [
    ['/nonexistent-baseline.json', /读取基线失败/],
    ['package.json', /缺少 groups 数组/],
  ]) {
    const child = spawnSync(
      process.execPath,
      ['scripts/report-duplicates.mjs', '--baseline', baseline],
      { encoding: 'utf8' },
    );
    assert.notEqual(child.status, 0);
    assert.match(child.stderr, message);
  }
});

test('基线对比识别新增、消失与成员变化', () => {
  const group = (language, fingerprint, members) => ({
    language,
    mode: 'exact',
    fingerprint,
    nodes: 10,
    coveredNodes: 20,
    fileCount: members.length,
    evidence: 'x',
    members: members.map(([path, startLine, endLine, symbol]) => ({
      path,
      startLine,
      endLine,
      symbol,
    })),
  });
  const same = group('go', 'aaa', [
    ['a.go', 1, 9, 'A'],
    ['b.go', 1, 9, 'B'],
  ]);
  const baseline = [same, group('go', 'gone', [['c.go', 1, 9, 'C']])];
  const grown = group('go', 'aaa', [
    ['a.go', 1, 9, 'A'],
    ['b.go', 1, 9, 'B'],
    ['d.go', 5, 13, 'D'],
  ]);
  const fresh = group('javascript', 'new', [['e.ts', 1, 9, 'E']]);
  const delta = baselineDelta([same, grown, fresh], baseline);
  assert.deepEqual(
    delta.added.map((item) => item.fingerprint),
    ['new'],
  );
  assert.deepEqual(
    delta.resolved.map((item) => item.fingerprint),
    ['gone'],
  );
  assert.equal(delta.changed.length, 1);
  assert.equal(delta.changed[0].current.members.length, 3);
  assert.equal(delta.changed[0].baseline.members.length, 2);
  const empty = baselineDelta([same], [same]);
  assert.deepEqual(empty, { added: [], resolved: [], changed: [] });
  const text = renderText({
    minNodes: 60,
    statistics: {
      scannedFiles: { javascript: 1, go: 1 },
      excludedFiles: {},
      excludedDirectories: 0,
      functions: 1,
      eligibleFunctions: 1,
      exactOnlyFunctions: 0,
    },
    limitations: [],
    groups: [fresh],
    errors: [],
    baseline: { path: 'base.json', ...delta },
  });
  assert.match(text, /新增 1 组、消失 1 组、成员变化 1 组/);
  assert.match(text, /\+ 新增 \[javascript\/exact\]/);
  assert.match(text, /- 消失 \[go\/exact\]/);
  assert.match(text, /~ 成员变化 \[go\/exact\]/);
  assert.match(text, /旧 a\.go:1-9 A/);
  assert.match(text, /新 d\.go:5-13 D/);
});
