// 凭据仅由未提交环境变量注入，日志不输出 Cookie、令牌或业务记录。
import { createRequire } from 'node:module';
import { writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';

const require = createRequire(`${process.cwd()}/web/package.json`);
const { chromium } = require('@playwright/test');
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, timezoneId: 'Asia/Shanghai' });
const page = await context.newPage();
page.setDefaultTimeout(20000);
const results = [];
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const base = 'http://127.0.0.1:8001';
const disableMotion = () => page.addStyleTag({ content: '*, *::before, *::after { animation-duration: 0s !important; transition-duration: 0s !important; }' });
try {
  assert(process.env.BOOTSTRAP_ADMIN_USERNAME && process.env.BOOTSTRAP_ADMIN_PASSWORD, '需要本地登录凭据');
  await page.goto(`${base}/user/login`);
  await page.getByText('账号登录', { exact: true }).click();
  await page.getByPlaceholder('钉钉手机号 / 本地账号').fill(process.env.BOOTSTRAP_ADMIN_USERNAME);
  await page.getByPlaceholder('请输入密码').fill(process.env.BOOTSTRAP_ADMIN_PASSWORD);
  await page.locator('button[type="submit"]').click();
  await page.getByRole('heading', { name: '选择进入的组织' }).waitFor();
  const meResponse = await page.request.get(`${base}/api/v1/auth/me`);
  assert(meResponse.ok(), '读取当前登录身份失败');
  const me = (await meResponse.json()).data;
  const company = me.organizations.find(organization => organization.kind === 2 && organization.baseCurrency === 'CNY');
  assert(company, '需要可用公司工作台');
  await page.getByRole('button', { name: `进入${company.name}`, exact: true }).click();
  await page.waitForURL(url => !url.pathname.includes('/user/login'));
  await page.goto(`${base}/orders/sea-export`);
  await disableMotion();
  await page.getByRole('button', { name: '列设置', exact: true }).first().click();
  const dialog = page.getByRole('dialog', { name: '列设置', exact: true });
  await dialog.waitFor();
  await dialog.hover({ position: { x: 50, y: 10 } });
  const dimensions = await dialog.evaluate(node => {
    const rect = node.getBoundingClientRect();
    return { width: rect.width, height: rect.height, x: rect.x, y: rect.y, viewport: { width: innerWidth, height: innerHeight } };
  });
  console.log(JSON.stringify({ dimensions }));
  await page.screenshot({ path: '/tmp/roncin-column-real-order.png' });
  assert(dimensions.width > 1000, '订单列表列设置应充分使用桌面视口');
  results.push({ name: '真实订单列表使用全局大面板', pass: true, dimensions });
  console.log(JSON.stringify(results.at(-1)));
  await dialog.getByRole('button', { name: /关闭|Close/ }).first().click();
  const listResponse = await page.request.get(`${base}/api/v1/orders?page=1&pageSize=20`);
  assert(listResponse.ok(), '读取现有订单失败');
  const listBody = (await listResponse.json()).data;
  const items = listBody?.items ?? listBody?.list ?? (Array.isArray(listBody) ? listBody : []);
  const order = items.find(item => item.id && (item.businessType === 1 || item.businessType === undefined));
  assert(order, '需要已存在的海运订单进行只读费用入口验收');
  await page.goto(`${base}/orders/sea-export/${encodeURIComponent(order.id)}/fees`);
  await disableMotion();
  await page.getByRole('button', { name: '列设置', exact: true }).first().click();
  await dialog.waitFor();
  await dialog.hover({ position: { x: 50, y: 10 } });
  const selectFreeze = async (key, label) => {
    await dialog.locator(`[data-column-key="${key}"]`).getByRole('combobox').click();
    await page.locator('.ant-select-dropdown:visible .ant-select-item-option').filter({ hasText: label }).click();
  };
  await selectFreeze('feeSettingId', '左冻结');
  await selectFreeze('settlementPartyId', '左冻结');
  assert.equal(await dialog.locator('[data-freeze-zone="left"] [data-column-key]').count(), 2);
  await dialog.getByRole('button', { name: /关闭|Close/ }).click();
  await dialog.waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: '列设置', exact: true }).nth(1).click();
  await dialog.waitFor();
  assert.equal(await dialog.locator('[data-freeze-zone="left"] [data-column-key]').count(), 2);
  results.push({ name: '真实费用应收应付共享两个左冻结字段', pass: true });
  console.log(JSON.stringify(results.at(-1)));
  await dialog.getByRole('button', { name: /关闭|Close/ }).click();
  await page.reload();
  await disableMotion();
  await page.getByRole('button', { name: '列设置', exact: true }).first().click();
  await dialog.waitFor();
  assert.equal(await dialog.locator('[data-freeze-zone="left"] [data-column-key]').count(), 2);
  await dialog.getByRole('button', { name: '恢复默认', exact: true }).click();
  assert.equal(await dialog.locator('[data-freeze-zone="left"] [data-column-key]').count(), 0);
  results.push({ name: '真实费用偏好刷新重读和恢复默认', pass: true });
  console.log(JSON.stringify(results.at(-1)));
  results.push({ name: '真实订单费用使用同一设置面板', pass: true });
  console.log(JSON.stringify(results.at(-1)));
} finally {
  await page.request.post(`${base}/api/v1/auth/logout`, { data: {} }).catch(() => {});
  await writeFile(new URL('./browser-real-pages.json', import.meta.url), JSON.stringify({ results, errors }, null, 2));
  await browser.close();
}
